const materialBody = document.getElementById("materialBody");
const resultCount = document.getElementById("resultCount");
const searchInput = document.getElementById("searchInput");
const searchBtn = document.getElementById("searchBtn");
const clearBtn = document.getElementById("clearBtn");
const noResults = document.getElementById("noResults");


/* =========================================================
   DISPLAY MATERIALS
========================================================= */

function displayMaterials(list) {

    materialBody.innerHTML = "";

    resultCount.textContent =
        list.length +
        " Material" +
        (list.length === 1 ? "" : "s");


    if (list.length === 0) {

        noResults.style.display = "block";

        return;
    }


    noResults.style.display = "none";


    list.forEach(function(material) {

        const row = document.createElement("tr");


        /* MATERIAL CODE */

        const codeCell =
            document.createElement("td");

        codeCell.className =
            "material-code";

        codeCell.textContent =
            material.code;


        /* MATERIAL NAME */

        const nameCell =
            document.createElement("td");

        nameCell.textContent =
            material.name;


        /* UOM */

        const uomCell =
            document.createElement("td");

        uomCell.textContent =
            material.uom;


        /* PREVIEW */

        const previewCell =
            document.createElement("td");


        if (
            material.link &&
            material.link.trim() !== ""
        ) {

            const preview =
                document.createElement("a");

            preview.className =
                "preview-btn";

            preview.textContent =
                "PREVIEW ↗";

            preview.href =
                material.link;

            preview.target =
                "_blank";

            preview.rel =
                "noopener noreferrer";

            previewCell.appendChild(
                preview
            );

        } else {

            previewCell.textContent =
                "No link";

        }


        /* ADD CELLS */

        row.appendChild(codeCell);
        row.appendChild(nameCell);
        row.appendChild(uomCell);
        row.appendChild(previewCell);


        /* ADD ROW */

        materialBody.appendChild(row);

    });

}


/* =========================================================
   SEARCH
========================================================= */

function searchMaterials() {

    const keyword =
        searchInput.value
            .trim()
            .toLowerCase();


    if (keyword === "") {

        displayMaterials(materials);

        return;
    }


    const results =
        materials.filter(function(material) {

            return (
                material.code
                    .toLowerCase()
                    .includes(keyword)

                ||

                material.name
                    .toLowerCase()
                    .includes(keyword)
            );

        });


    displayMaterials(results);

}


/* =========================================================
   CLEAR
========================================================= */

function clearSearch() {

    searchInput.value = "";

    displayMaterials(materials);

    searchInput.focus();

}


/* =========================================================
   BUTTONS
========================================================= */

searchBtn.addEventListener(
    "click",
    searchMaterials
);

clearBtn.addEventListener(
    "click",
    clearSearch
);


/* =========================================================
   ENTER KEY
========================================================= */

searchInput.addEventListener(
    "keydown",
    function(event) {

        if (event.key === "Enter") {

            searchMaterials();

        }

    }
);


